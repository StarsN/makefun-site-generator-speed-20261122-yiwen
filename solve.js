/** A template that does not parse: its name and why. */
class TemplateError extends Error {}

const PATH_RE = /^[A-Za-z_][A-Za-z0-9_]*(?:\.[A-Za-z_][A-Za-z0-9_]*)*$/;
const FOR_RE = /^for ([A-Za-z_][A-Za-z0-9_]*) in (\S+)$/;
const IF_RE = /^if (not )?(\S+)$/;
const INCLUDE_RE = /^include "([a-z0-9-]+)"$/;

/** The path `text` names, split at its dots, or a TemplateError. */
function pathOf(name, text) {
  if (!PATH_RE.test(text)) throw new TemplateError(`template "${name}": ${JSON.stringify(text)} is not a path`);
  return text.split('.');
}

/** `src`'s tokens: text, {{ }}, {{{ }}} and {% %}, a standalone tag's line taken with it. */
function tokenize(name, src) {
  const tokens = [];
  let text = '';
  let i = 0;
  while (i < src.length) {
    const open = src.indexOf('{', i);
    if (open === -1 || open === src.length - 1) { text += src.slice(i); break; }
    const next = src[open + 1];
    if (next !== '{' && next !== '%') { text += src.slice(i, open + 1); i = open + 1; continue; }
    text += src.slice(i, open);
    if (next === '{') {
      const raw = src[open + 2] === '{';
      const close = src.indexOf(raw ? '}}}' : '}}', open + (raw ? 3 : 2));
      if (close === -1) throw new TemplateError(`template "${name}": a ${raw ? '{{{' : '{{'} is not closed`);
      if (text !== '') tokens.push({ t: 'text', text });
      text = '';
      tokens.push({ t: raw ? 'raw' : 'var', path: pathOf(name, src.slice(open + (raw ? 3 : 2), close).trim()) });
      i = close + (raw ? 3 : 2);
      continue;
    }
    const close = src.indexOf('%}', open + 2);
    if (close === -1) throw new TemplateError(`template "${name}": a {% is not closed`);
    const end = close + 2;
    const lineStart = src.lastIndexOf('\n', open - 1) + 1;
    const nl = src.indexOf('\n', end);
    const lineEnd = nl === -1 ? src.length : nl;
    const standalone = /^[ \t]*$/.test(src.slice(lineStart, open)) && /^[ \t]*$/.test(src.slice(end, lineEnd));
    if (standalone) text = text.slice(0, text.length - (open - lineStart));
    if (text !== '') tokens.push({ t: 'text', text });
    text = '';
    tokens.push({ t: 'tag', tag: src.slice(open + 2, close).trim() });
    i = standalone ? (nl === -1 ? src.length : nl + 1) : end;
  }
  if (text !== '') tokens.push({ t: 'text', text });
  return tokens;
}

/** `src` parsed into its tree of nodes (a TemplateError when it does not parse). */
function parseTemplate(name, src) {
  const root = { kind: 'root', body: [] };
  const stack = [root];
  let body = root.body;
  for (const tok of tokenize(name, src)) {
    if (tok.t === 'text') body.push({ kind: 'text', text: tok.text });
    else if (tok.t === 'var' || tok.t === 'raw') body.push({ kind: tok.t, path: tok.path });
    else {
      const tag = tok.tag;
      const top = stack[stack.length - 1];
      let m;
      if ((m = FOR_RE.exec(tag)) !== null) {
        const node = { kind: 'for', name: m[1], path: pathOf(name, m[2]), body: [] };
        body.push(node);
        stack.push(node);
        body = node.body;
      } else if ((m = IF_RE.exec(tag)) !== null) {
        const node = { kind: 'if', not: m[1] !== undefined, path: pathOf(name, m[2]), then: [], else: null };
        body.push(node);
        stack.push(node);
        body = node.then;
      } else if (tag === 'else') {
        if (top.kind !== 'if' || top.else !== null) throw new TemplateError(`template "${name}": an else outside an if`);
        top.else = [];
        body = top.else;
      } else if (tag === 'endfor' || tag === 'endif') {
        if (top.kind !== (tag === 'endfor' ? 'for' : 'if')) throw new TemplateError(`template "${name}": an ${tag} with no open ${tag.slice(3)}`);
        stack.pop();
        const parent = stack[stack.length - 1];
        body = parent.kind === 'root' ? parent.body : parent.kind === 'for' ? parent.body : parent.else ?? parent.then;
      } else if ((m = INCLUDE_RE.exec(tag)) !== null) body.push({ kind: 'include', name: m[1] });
      else throw new TemplateError(`template "${name}": {% ${tag} %} is not a tag`);
    }
  }
  if (stack.length > 1) throw new TemplateError(`template "${name}": a ${stack[stack.length - 1].kind} is not closed`);
  return root.body;
}

// --- template runtime helpers (shared by every compiled template) ---

/** The value at `name` in the scope chain: the nearest scope holding it. */
function LK(SC, name) {
  for (let i = SC.length - 1; i >= 0; i--) {
    const v = SC[i];
    if (Object.hasOwn(v, name)) return v[name];
  }
  return undefined;
}

/** One own-property step of a path, or undefined. */
function GO(v, k) {
  return v !== null && typeof v === 'object' && Object.hasOwn(v, k) ? v[k] : undefined;
}

/** A value as text: a string itself, a number in JavaScript's digits, true or false, an array's items joined by ", ", else "". */
function TX(v) {
  if (typeof v === 'string') return v;
  if (typeof v === 'number') return String(v);
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (Array.isArray(v)) return v.map(TX).join(', ');
  return '';
}

/** Whether a value counts as true in an if. */
function TR(v) {
  if (Array.isArray(v)) return v.length > 0;
  return v !== undefined && v !== null && v !== false && v !== '' && v !== 0;
}

const INCLUDE_DEPTH = 8;

/** Whether a node tree holds an include anywhere (then a for must keep its scope on the chain). */
function hasInclude(nodes) {
  for (const n of nodes) {
    if (n.kind === 'include') return true;
    if (n.kind === 'for' && hasInclude(n.body)) return true;
    if (n.kind === 'if' && (hasInclude(n.then) || (n.else !== null && hasInclude(n.else)))) return true;
  }
  return false;
}

/**
 * A node tree compiled to a function (SC, OUT, DE, LK, GO, TX, TR, ES, TPL):
 * SC is the scope chain (innermost last), OUT the output chunks, DE the include
 * depth, TPL the map of compiled templates. Loop variables are plain JS locals;
 * any other first name is read from the chain, exactly as the reference does.
 */
function compileTemplate(nodes) {
  let uid = 0;
  const code = [];
  const gen = (ns, lex) => {
    let pending = '';
    const flush = () => {
      if (pending !== '') { code.push(`OUT.push(${JSON.stringify(pending)});`); pending = ''; }
    };
    for (const n of ns) {
      if (n.kind === 'text') { pending += n.text; continue; }
      flush();
      if (n.kind === 'var' || n.kind === 'raw') {
        const e = pathExpr(n.path, lex);
        code.push(n.kind === 'var' ? `OUT.push(ES(TX(${e})));` : `OUT.push(TX(${e}));`);
      } else if (n.kind === 'if') {
        code.push(`if(TR(${pathExpr(n.path, lex)})!==${n.not ? 'true' : 'false'}){`);
        gen(n.then, lex);
        if (n.else !== null) { code.push('}else{'); gen(n.else, lex); }
        code.push('}');
      } else if (n.kind === 'for') {
        const id = uid++;
        const av = `A${id}`;
        const iv = `I${id}`;
        const nv = `N${id}`;
        const vv = `V${id}`;
        const lv = `L${id}`;
        const sv = `S${id}`;
        code.push(`{const ${av}=${pathExpr(n.path, lex)};if(Array.isArray(${av})){const ${nv}=${av}.length;for(let ${iv}=0;${iv}<${nv};${iv}++){const ${vv}=${av}[${iv}];const ${lv}={index:${iv}+1,first:${iv}===0,last:${iv}===${nv}-1,length:${nv}};`);
        const inner = { ...lex, [n.name]: vv, loop: lv };
        if (hasInclude(n.body)) {
          code.push(`const ${sv}={};${sv}[${JSON.stringify(n.name)}]=${vv};${sv}.loop=${lv};SC.push(${sv});`);
          gen(n.body, inner);
          code.push('SC.pop();');
        } else {
          gen(n.body, inner);
        }
        code.push('}}}');
      } else if (n.kind === 'include') {
        code.push(`if(DE<${INCLUDE_DEPTH}){const T=TPL.get(${JSON.stringify(n.name)});if(T!==undefined)T(SC,OUT,DE+1,LK,GO,TX,TR,ES,TPL);}`);
      }
    }
    flush();
  };
  const pathExpr = (path, lex) => {
    const first = path[0];
    let e = Object.hasOwn(lex, first) ? lex[first] : `LK(SC,${JSON.stringify(first)})`;
    for (let k = 1; k < path.length; k++) e = `GO(${e},${JSON.stringify(path[k])})`;
    return e;
  };
  gen(nodes, {});
  return new Function('SC', 'OUT', 'DE', 'LK', 'GO', 'TX', 'TR', 'ES', 'TPL', code.join('\n'));
}

/** Render template `name` with `vars` (null when the template is missing). */
function renderTemplate(name, vars) {
  const fn = TPLS.get(name);
  if (fn === undefined) return null;
  const out = [];
  fn([vars], out, 0, LK, GO, TX, TR, escStr, TPLS);
  return out.join('');
}

